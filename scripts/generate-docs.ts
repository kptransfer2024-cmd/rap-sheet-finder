/**
 * Generates docs from the live registries so docs never drift from code:
 *   docs/decision-tree.mmd          Mermaid graph (questions -> rules -> outcomes)
 *   docs/decision-tree-outline.md   accessible text equivalent of the graph
 *   docs/provenance_matrix.md       rule -> outcome -> step -> facts/sources -> status
 * Usage: npm run docs:graph
 */
import { writeFileSync } from 'node:fs';
import { FACT_BY_ID } from '../src/data/facts';
import { RESOURCE_BY_ID } from '../src/data/resources';
import { OUTCOME_BY_ID, OUTCOMES } from '../src/domain/outcomes';
import { QUESTIONS } from '../src/domain/questions';
import { ALERT_RULES, FALLBACK_OUTCOME_ID, FALLBACK_RULE_ID, RULES } from '../src/domain/rules';
import type { Condition } from '../src/domain/types';

function cond(c: Condition | undefined): string {
  if (!c || 'always' in c) return 'always';
  if ('all' in c) return c.all.map(cond).join(' AND ');
  if ('any' in c) return `(${c.any.map(cond).join(' OR ')})`;
  if ('not' in c) return `NOT ${cond(c.not)}`;
  const q = `${c.q}${c.scope === 'case' ? '@case' : ''}`;
  if ('answered' in c) return `${q} ${c.answered ? 'answered' : 'unanswered'}`;
  if ('only' in c) return `${q} only ${c.only.join('|')}`;
  return `${q} in ${c.in.join('|')}`;
}
const esc = (s: string) => s.replace(/"/g, "'").replace(/[<>]/g, '');
const nid = (s: string) => s.replace(/[^A-Za-z0-9]/g, '_');

// ---------------------------------------------------------------- Mermaid
const m: string[] = [];
m.push('%% GENERATED by scripts/generate-docs.ts from src/domain/{questions,rules,outcomes}.ts — do not edit by hand.');
m.push('flowchart TD');
m.push('  START([Start: welcome screen]) --> whose_record');
m.push('  subgraph Q["Questions — asked in order, skipped when the condition is false; unanswered = \'not sure\'"]');
QUESTIONS.forEach((q, i) => {
  const scope = q.scope === 'case' ? ' ⟲ per case' : '';
  m.push(`    ${nid(q.id)}["${q.bankRefs.join('/')} ${q.id}${scope}<br/><i>${esc(cond(q.askIf))}</i>"]`);
  if (i > 0) m.push(`    ${nid(QUESTIONS[i - 1].id)} -.-> ${nid(q.id)}`);
});
m.push('  end');
m.push(`  ${nid(QUESTIONS[QUESTIONS.length - 1].id)} --> ENGINE{{"Rule engine: evaluate every rule; highest priority = Start here"}}`);
m.push('  subgraph R["Rules → outcome cards (priority)"]');
for (const r of RULES) {
  m.push(`    ${nid(r.id)}{"${r.id} p${r.priority}${r.scope === 'case' ? ' per case' : ''}"}`);
  m.push(`    ${nid(r.id)} --> ${nid(r.emit)}`);
}
m.push(`    ${nid(FALLBACK_RULE_ID)}{"${FALLBACK_RULE_ID} (no rule matched)"} --> ${nid(FALLBACK_OUTCOME_ID)}`);
m.push('  end');
m.push(`  ENGINE --> R`);
for (const o of OUTCOMES) m.push(`  ${nid(o.id)}[["${o.id}<br/>${esc(o.shortTitle.en)}<br/><b>${o.status}</b>"]]`);
m.push('  classDef outcome fill:#dbeae5,stroke:#0e5a57;');
m.push(`  class ${OUTCOMES.map((o) => nid(o.id)).join(',')} outcome;`);
writeFileSync('docs/decision-tree.mmd', m.join('\n') + '\n');

// ---------------------------------------------------------------- Text outline
const t: string[] = [];
t.push('# Decision tree — text outline');
t.push('');
t.push('> Generated by `npm run docs:graph` from the live registries. Accessible equivalent of `decision-tree.mmd`.');
t.push('');
t.push('## How routing works');
t.push('');
t.push('1. Questions are asked **in the order below**. Each is skipped unless its condition holds. A condition may only refer to earlier questions, so the graph cannot loop.');
t.push('2. Per-case questions (⟲) repeat for Santa Clara case 1 and 2 (or once for "three or more / not sure").');
t.push('3. Any applicable question left unanswered (skipped, or "Show my plan now") is treated as its **"not sure"** option — never as "no".');
t.push('4. Every rule whose condition holds adds an outcome card. The highest-priority card is shown as **Start here**; ties break by case number, then outcome id.');
t.push('5. If no rule matches, `R-FALLBACK` shows `CANNOT_DETERMINE` (safe starting points + help).');
t.push('');
t.push('## Questions');
t.push('');
QUESTIONS.forEach((q, i) => {
  t.push(`${i + 1}. **${q.id}**${q.scope === 'case' ? ' ⟲ per case' : ''}${q.optional ? ' (optional)' : ''} — ${q.bankRefs.join(', ')} — "${q.prompt.en}"`);
  t.push(`   - Asked when: \`${cond(q.askIf)}\``);
  t.push(`   - Options: ${q.options.map((o) => `\`${o.code}\`${o.code === q.unknownCode ? ' (default if unanswered)' : ''}`).join(', ')}`);
});
t.push('');
t.push('## Rules');
t.push('');
t.push('| Rule | Scope | Priority | When | Emits | Alerts |');
t.push('|---|---|---|---|---|---|');
for (const r of RULES) t.push(`| ${r.id} | ${r.scope} | ${r.priority} | \`${cond(r.when)}\` | ${r.emit} | ${(r.alerts ?? []).join(', ')} |`);
t.push(`| ${FALLBACK_RULE_ID} | global | 1 | no other rule matched | ${FALLBACK_OUTCOME_ID} | |`);
for (const a of ALERT_RULES) t.push(`| ${a.id} | global | — | \`${cond(a.when)}\` | (alert only) | ${a.alert} |`);
t.push('');
t.push('## Outcomes');
t.push('');
for (const o of OUTCOMES) t.push(`- **${o.id}** (${o.category}, ${o.status}) — ${o.shortTitle.en}. Steps: ${o.steps.map((s) => s.id + (s.when ? '*' : '')).join(', ')}  _(* = conditional)_`);
writeFileSync('docs/decision-tree-outline.md', t.join('\n') + '\n');

// ---------------------------------------------------------------- Provenance matrix
const p: string[] = [];
p.push('# Provenance matrix');
p.push('');
p.push('> Generated by `npm run docs:graph`. Every rule → outcome → step, with the facts and official sources behind it and their status.');
p.push('> **verified** = this build re-read the official page on the date shown; **partial** = from earlier research (Nov 7 matrix / Nov 22 handoff) or partly confirmed; **needs_review** = unknown, conflicting, or the page blocked automated checking. Steps citing no source are labeled *UX convention*.');
p.push('');
p.push('## Rules → outcomes');
p.push('');
p.push('| Rule | Emits | Plain-language reason |');
p.push('|---|---|---|');
for (const r of RULES) p.push(`| ${r.id} | ${r.emit} | ${r.explain.en} |`);
p.push('');
p.push('## Outcome steps → facts & sources');
for (const o of OUTCOMES) {
  p.push('');
  p.push(`### ${o.id} — ${o.shortTitle.en}`);
  p.push('');
  p.push('| Step | Facts (status) | Sources (status, checked) |');
  p.push('|---|---|---|');
  for (const s of o.steps) {
    const facts = (s.factIds ?? []).map((f) => `${f} (${FACT_BY_ID[f].status}${FACT_BY_ID[f].kind === 'caveat' ? ', caveat' : ''})`).join('<br>') || '—';
    const srcs =
      s.officialResources.map((r) => `${r} (${RESOURCE_BY_ID[r].verificationStatus}${RESOURCE_BY_ID[r].lastCheckedByBuild ? `, ${RESOURCE_BY_ID[r].lastCheckedByBuild}` : ''})`).join('<br>') ||
      '—';
    const conv = !s.factIds?.length && !s.officialResources.length ? ' *(UX convention)*' : '';
    p.push(`| ${s.id}${conv} | ${facts} | ${srcs} |`);
  }
}
p.push('');
p.push('## Facts');
p.push('');
p.push('| Fact | Status | Checked | Sources | Conflict / note |');
p.push('|---|---|---|---|---|');
for (const f of Object.values(FACT_BY_ID))
  p.push(`| ${f.id}${f.kind === 'caveat' ? ' (caveat)' : ''} | ${f.status} | ${f.checkedAt ?? '—'} | ${f.sourceIds.join(', ')} | ${(f.conflict ?? f.note ?? '').replace(/\|/g, '/')} |`);
writeFileSync('docs/provenance_matrix.md', p.join('\n') + '\n');

console.log(`Wrote docs/decision-tree.mmd, docs/decision-tree-outline.md, docs/provenance_matrix.md (${QUESTIONS.length} questions, ${RULES.length} rules, ${OUTCOMES.length} outcomes; outcome ids valid: ${RULES.every((r) => OUTCOME_BY_ID[r.emit])})`);
